function iconDots(name) {
    return litDots(icons[name]);
}

function displayGlyph(ch) {
    const glyph = display[ch];
    if (!glyph)
        return null;
    return {
        pitch: glyph.pitch,
        dot: glyph.dot,
        columns: glyph.rows[0].length,
        rows: glyph.rows.length,
        dots: litDots(glyph.rows)
    };
}

function litDots(rows) {
    if (!rows)
        return [];
    const dots = [];
    for (let y = 0; y < rows.length; y++)
        for (let x = 0; x < rows[y].length; x++)
            if (rows[y][x] === "#")
                dots.push({ x: x, y: y });
    return dots;
}

function digitLit(ch, x, y) {
    const rows = digits[ch];
    return !!rows && rows[y][x] === "1";
}
